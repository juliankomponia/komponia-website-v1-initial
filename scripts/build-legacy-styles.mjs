import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';
import selectorParser from 'postcss-selector-parser';

// Compile historical page helpers first, then contain every selector. This keeps
// their established appearance without leaking old styles into the new homepage.
const files = [
  'src/orig.css', 'src/komponia-refinements.css', 'src/brand.css',
  'src/components/PageSections.css', 'src/views/components.css',
  'src/views/contact.css', 'src/views/home.css', 'src/views/homepage.css',
];
const source = '@tailwind components;\n' + (await Promise.all(files.map(file => readFile(file, 'utf8')))).join('\n');
const compiled = await postcss([tailwindcss(path.resolve('tailwind.config.js'))]).process(source, { from: 'src/legacy-source.css' });
compiled.root.walkAtRules('font-face', rule => rule.remove());
compiled.root.walkRules(rule => {
  for (let parent = rule.parent; parent; parent = parent.parent) {
    if (parent.type === 'atrule' && /keyframes$/.test(parent.name)) return;
  }
  rule.selector = selectorParser(selectors => {
    selectors.each(selector => {
      const first = selector.nodes[0];
      if ((first.type === 'pseudo' && first.value === ':root') || (first.type === 'tag' && ['html', 'body'].includes(first.value))) {
        first.replaceWith(selectorParser.className({ value: 'legacy-pages' }));
      } else {
        selector.prepend(selectorParser.combinator({ value: ' ' }));
        selector.prepend(selectorParser.className({ value: 'legacy-pages' }));
      }
    });
  }).processSync(rule.selector);
});
await writeFile('src/app/legacy.generated.css', '/* Generated by scripts/build-legacy-styles.mjs. Edit the historical CSS sources. */\n' + compiled.root.toString());
console.log('Historical page styles compiled and scoped to .legacy-pages.');
